import { test, expect, type Page } from '@playwright/test'

async function createTask(page: Page, title: string, date?: string) {
  await page.getByRole('button', { name: '新建任务', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('任务名称').fill(title)
  if (date) await dialog.getByLabel('安排日期').fill(date)
  await dialog.getByRole('button', { name: '保存任务', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}
test('create, expand, rapid substeps, status, reload offline, search and restore', async ({ page, context }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.waitForFunction(() => !!navigator.serviceWorker.controller)
  await expect(page.getByRole('heading', { name: '留白的一天，有无限可能' })).toBeVisible()
  await page.getByRole('button', { name: '新建任务', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('任务名称').fill('研究任务 E2E')
  await dialog.getByLabel('备注', { exact: true }).fill('测试离线与子步骤')
  for (const title of ['阅读论文', '记录问题']) {
    await dialog.getByRole('button', { name: '添加步骤' }).click()
    await dialog.getByPlaceholder('一个明确的小步骤').last().fill(title)
  }
  await dialog.getByRole('button', { name: '保存任务' }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  if (await page.getByRole('button', { name: '展开：研究任务 E2E' }).count()) await page.getByRole('button', { name: '展开：研究任务 E2E' }).click()
  await page.getByLabel('阅读论文', { exact: true }).click()
  await page.getByLabel('记录问题', { exact: true }).click()
  await expect(page.getByLabel('阅读论文', { exact: true })).toBeChecked()
  await page.getByRole('combobox', { name: '更改状态：研究任务 E2E' }).selectOption('doing')
  await expect(page.locator('.group-doing').getByTestId('task-row')).toHaveCount(1)
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('button', { name: '展开：研究任务 E2E' }).click()
  await expect(page.getByLabel('阅读论文', { exact: true })).toBeChecked()
  await expect(page.getByLabel('记录问题', { exact: true })).toBeChecked()
  await context.setOffline(false)
  await page.getByRole('button', { name: '删除：研究任务 E2E' }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  await page.getByRole('button', { name: '打开设置', exact: true }).click()
  await page.getByRole('button', { name: '回收站', exact: true }).click()
  await page.getByRole('button', { name: '恢复任务', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  if (await page.getByRole('button', { name: '跳转到今天' }).isVisible()) await page.getByRole('button', { name: '跳转到今天' }).click()
  else await page.getByRole('button', { name: '今天', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索任务' }).fill('研究任务')
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.getByRole('button', { name: '完成：研究任务 E2E' }).click()
  await expect(page.locator('.group-done').getByTestId('task-row')).toHaveCount(1)
  expect(errors).toEqual([])
})
test('future dates and persisted group folding', async ({ page }, testInfo) => {
  await page.goto('/')
  await createTask(page, '未来计划', '2027-01-15')
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '全部', exact: true }).click()
  else await page.getByRole('button', { name: '全部任务', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.locator('.group-todo > .group-heading').click()
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  await page.reload()
  if (testInfo.project.name === 'mobile') await page.getByRole('button', { name: '全部', exact: true }).click()
  else await page.getByRole('button', { name: '全部任务', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  await page.locator('.group-todo > .group-heading').click()
  await expect(page.getByTestId('task-row')).toHaveCount(1)
})
