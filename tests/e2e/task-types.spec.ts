import { test, expect } from '@playwright/test'

test('planned work and incidental issues remain distinct through status changes, filtering, editing, reload, and compact mode', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新建任务', exact: true }).first().click()
  await page.getByLabel('任务名称').fill('计划内工作')
  await expect(page.getByRole('radio', { name: '计划任务', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  await page.getByRole('button', { name: '筛选：零碎问题', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  await page.getByRole('button', { name: '新建任务', exact: true }).first().click()
  await expect(page.getByRole('radio', { name: '零碎问题', exact: true })).toBeChecked()
  await page.getByLabel('任务名称').fill('修复蓝牙断连')
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  const issue = page.getByTestId('task-row').filter({ hasText: '修复蓝牙断连' })
  await expect(issue).toHaveAttribute('data-task-kind', 'issue')
  await expect(issue.getByRole('img', { name: '零碎问题', exact: true })).toBeVisible()
  await issue.getByRole('button', { name: '展开：修复蓝牙断连' }).click()
  await issue.getByRole('combobox', { name: '更改状态：修复蓝牙断连' }).selectOption('doing')
  await expect(page.locator('.group-doing').getByTestId('task-row')).toHaveAttribute('data-task-kind', 'issue')
  await page.reload()
  await expect(page.getByRole('button', { name: '筛选：零碎问题' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.getByRole('button', { name: '切换精简视图' }).click()
  await expect(issue.getByRole('img', { name: '零碎问题', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '完成：修复蓝牙断连' }).click()
  await expect(page.locator('.group-done').getByTestId('task-row')).toHaveAttribute('data-task-kind', 'issue')
  await page.getByRole('button', { name: '展开：修复蓝牙断连' }).click()
  await issue.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByRole('radio', { name: '计划任务', exact: true }).check()
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(0)
  await page.getByRole('button', { name: '筛选：计划任务', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(2)
  await expect(page.locator('.group-done').getByTestId('task-row')).toHaveAttribute('data-task-kind', 'planned')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
