import {test,expect} from '@playwright/test'
test.use({timezoneId:'America/Chicago'})
test('quick alarm and task deadlines use Beijing time and survive editing, filtering, reload and completion',async({page})=>{
  await page.clock.install({time:new Date('2026-10-21T07:00:00Z')})
  await page.goto('/')
  await page.getByRole('button',{name:'快捷闹钟',exact:true}).filter({visible:true}).click()
  const alarm=page.getByRole('dialog',{name:'快捷闹钟',exact:true})
  await alarm.getByLabel('提醒内容').fill('到点提交报告')
  await alarm.getByLabel('闹钟北京时间').fill('2026-10-21T14:59')
  await alarm.getByRole('button',{name:'设置提醒',exact:true}).click()
  await expect(alarm.getByRole('alert')).toContainText('未来')
  await alarm.getByRole('button',{name:'+5 分钟',exact:true}).click()
  await expect(alarm.getByLabel('闹钟北京时间')).toHaveValue('2026-10-21T15:05')
  await alarm.getByRole('button',{name:'设置提醒',exact:true}).click()
  const row=page.getByTestId('task-row').filter({hasText:'到点提交报告'})
  await expect(row).toHaveAttribute('data-task-kind','alarm')
  await expect(row).toContainText('15:05 提醒')
  const saved=await page.evaluate(async()=>{const db=await new Promise<IDBDatabase>(resolve=>{const r=indexedDB.open('dayweave-v1');r.onsuccess=()=>resolve(r.result)});const records=await new Promise<{task:{title:string;reminderAt:string;kind:string}}[]>(resolve=>{const r=db.transaction('records').objectStore('records').getAll();r.onsuccess=()=>resolve(r.result)});db.close();return records.find(r=>r.task.title==='到点提交报告')!.task})
  expect(saved.reminderAt).toBe('2026-10-21T07:05:00.000Z');expect(saved.kind).toBe('planned')
  await page.locator('.new-task').click()
  const edit=page.getByRole('dialog')
  await edit.getByLabel('任务名称').fill('普通任务有截止')
  await edit.getByLabel('截止时间（北京时间）').fill('2026-10-21T16:00')
  await edit.getByLabel('提前提醒').selectOption('15')
  await edit.getByRole('button',{name:'保存任务',exact:true}).click()
  await expect(page.getByTestId('task-row').filter({hasText:'普通任务有截止'})).toContainText('16:00 截止')
  await page.getByRole('button',{name:'筛选：闹钟',exact:true}).click();await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.reload();await expect(row).toBeVisible()
  await page.getByRole('button',{name:'展开：到点提交报告',exact:true}).click();await page.getByRole('button',{name:'编辑',exact:true}).click()
  await expect(page.getByLabel('截止时间（北京时间）')).toHaveValue('2026-10-21T15:05')
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
  await page.getByRole('button',{name:'完成：到点提交报告',exact:true}).click()
  await expect(row).toHaveClass(/is-done/)
})
