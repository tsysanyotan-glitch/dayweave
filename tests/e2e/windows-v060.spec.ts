  page.on('pageerror', e => errors.push(e.message)); page.on('request', r => { if (r.method() === 'POST' && r.url().includes('/storage/v1/')) uploads.push(r.url()) })
  await page.goto('/'); await page.locator('.new-task').click(); await page.getByLabel('任务名称').fill('并行项目')
  await page.getByRole('button', { name: '颜色', exact: true }).click(); await page.getByLabel('背景颜色 4', { exact: true }).click()
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
