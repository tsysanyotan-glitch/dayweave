  await page.reload(); await expect(page.getByTestId('task-row')).toHaveCSS('background-color', 'rgb(247, 226, 218)')
  await edit(page); await page.getByRole('button', { name: '上传并制作背景' }).click()
  const fixture = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 1200; c.height = 600; const ctx = c.getContext('2d')!; ctx.fillStyle = '#ff0000'; ctx.fillRect(0,0,600,600); ctx.fillStyle = '#0000ff'; ctx.fillRect(600,0,600,600); return c.toDataURL('image/png').split(',')[1] })
  const maker = page.getByRole('dialog', { name: '制作任务背景', exact: true })
  await maker.getByLabel('上传背景原图').setInputFiles({ name: '双色背景.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') })
  await expect(maker.getByAltText('背景原图')).toBeVisible()
