  const pixels = await page.evaluate(async () => { const db = await new Promise<IDBDatabase>(resolve => { const r = indexedDB.open('dayweave-appearance-v1'); r.onsuccess = () => resolve(r.result) }); const b = await new Promise<{dataUrl:string;width:number;height:number;opacity:number}[]>(resolve => { const r = db.transaction('backgrounds').objectStore('backgrounds').getAll(); r.onsuccess=()=>resolve(r.result) }); db.close(); const img=new Image();img.src=b[0].dataUrl;await img.decode();const c=document.createElement('canvas');c.width=1;c.height=1;c.getContext('2d')!.drawImage(img,0,0,1,1);return { ...b[0],dataUrl:undefined,pixel:[...c.getContext('2d')!.getImageData(0,0,1,1).data] } })
