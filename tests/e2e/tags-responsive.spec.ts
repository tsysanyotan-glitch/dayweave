import { test, expect } from '@playwright/test'

test('custom executor tags can be created, reused, filtered and edited without a collaboration section', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Agent 协作', exact: true })).toHaveCount(0)
  await page.locator('.new-task').click()
  await page.getByLabel('任务名称').fill('自定义执行者任务')
  await page.getByLabel('执行者', { exact: true }).fill('codex-研究')
  await expect(page.getByText('保存任务时创建「codex-研究」标签', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  await page.reload()
  await page.locator('.new-task').click()
  await page.getByLabel('任务名称').fill('复用执行者任务')
  await page.getByRole('button', { name: 'codex-研究', exact: true }).click()
  await expect(page.getByLabel('执行者', { exact: true })).toHaveValue('codex-研究')
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  await page.getByLabel('筛选执行者').selectOption('codex-研究')
  await expect(page.getByTestId('task-row')).toHaveCount(2)
  await page.getByRole('button', { name: '展开：复用执行者任务' }).click()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByLabel('执行者', { exact: true }).fill('自己')
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await page.getByLabel('筛选执行者').selectOption('all')
  await page.getByRole('button', { name: '完成：复用执行者任务' }).click()
  const nav = page.getByRole('navigation', { name: info.project.name === 'mobile' ? '手机导航' : '主导航' })
  await nav.getByRole('button', { name: '已结束', exact: true }).click()
  await expect(page.getByTestId('task-row')).toHaveCount(1)
  await expect(page.getByTestId('task-row')).toContainText('复用执行者任务')
})

test('compact and full content adapts to narrow, short and expanded windows with reachable controls', async ({ page }, info) => {
  await page.goto('/')
  await page.locator('.new-task').click()
  const title = '检查一个很长的任务标题与项目文件夹产出并确保小窗口仍可完整阅读'
  await page.getByLabel('任务名称').fill(title)
  await page.getByLabel('执行者', { exact: true }).fill('codex-一个很长的执行者标签')
  await page.getByLabel('备注', { exact: true }).fill('任务备注与产出在精简窗口中仍可展开查看。')
  await page.getByRole('button', { name: '添加步骤' }).click()
  await page.getByPlaceholder('一个明确的小步骤').fill('完成后查看结果')
  await page.getByRole('button', { name: '保存任务', exact: true }).click()
  await page.getByRole('button', { name: '切换精简视图' }).click()
  for (const [width, height] of [[280, 260], [360, 420], [520, 600], [820, 700]]) {
    await page.setViewportSize({ width, height })
    await expect(page.locator('.task-title')).toContainText(title)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: '展开：' + title }).click()
    await expect(page.getByLabel('完成后查看结果', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '折叠：' + title }).click()
    await page.getByRole('button', { name: '打开设置', exact: true }).click()
    const dialog = page.getByRole('dialog')
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    await dialog.getByRole('button', { name: '关闭窗口' }).click()
    if (info.project.name === 'desktop') {
      await page.addStyleTag({ content: '.task-row{content-visibility:visible}' })
      await page.screenshot({ path: `artifacts/compact-v3-${width}.png`, fullPage: true })
    }
  }
  await page.setViewportSize({ width: 320, height: 360 })
  await page.getByRole('button', { name: '恢复完整视图' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '打开设置', exact: true }).click()
  await expect(page.getByRole('button', { name: '回收站', exact: true })).toBeVisible()
})
